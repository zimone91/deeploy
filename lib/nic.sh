#!/usr/bin/env bash
# ============================================================================
# DeePloy — lib/nic.sh   (NIC setup layer; runs after tuning/validatorcfg,
# Before=solana.service). Driver-specific, mandated for XDP-retransmit boxes:
#   mlx5_core -> mlx5-irq-affinity.service: keep the NIC's mlx5 IRQs off the
#               isolated CPUs, except each XDP core's own queue IRQ, which
#               stays on that core. The map is computed at boot.
#   bnxt_en   -> nic-tuning.service: ring 512/512 (default 511 breaks XDP) +
#               disable gro/lro/gso/tso; then a pre-flight ZC compatibility test
#               (anza-xyz/agave-xdp-compatibility) before the validator starts.
#   other     -> nothing (retransmit already omitted).
#
# The interface is computed at RUNTIME inside the generated scripts
# (ip route show default), never hardcoded. Requires: common.sh sourced.
# ============================================================================

[[ -n "${_DEEPLOY_NIC_SOURCED:-}" ]] && return 0
_DEEPLOY_NIC_SOURCED=1

XDP_COMPAT_REPO="${XDP_COMPAT_REPO:-https://github.com/anza-xyz/agave-xdp-compatibility}"

nic_resolve_config() {
    SOLANA_HOME="$(state_get solana_home /root/solana)"
    NIC_DRIVER="$(state_get nic_driver "${NIC_DRIVER:-}")"
    MLX5_IRQ_SCRIPT="${MLX5_IRQ_SCRIPT:-$SOLANA_HOME/mlx5-irq-affinity.sh}"
    MLX5_IRQ_SERVICE="${MLX5_IRQ_SERVICE:-/etc/systemd/system/mlx5-irq-affinity.service}"
    NIC_TUNING_SCRIPT="${NIC_TUNING_SCRIPT:-$SOLANA_HOME/nic-tuning.sh}"
    NIC_TUNING_SERVICE="${NIC_TUNING_SERVICE:-/etc/systemd/system/nic-tuning.service}"
    XDP_COMPAT_SRC="${XDP_COMPAT_SRC:-$HOME/agave-xdp-compatibility}"
}

# --- mlx5: IRQ affinity ------------------------------------------------------
# The mlx5 driver points mlx5_comp<i> at CPU i, isolated CPUs included. A map
# hardcoded for PoH=10 / XDP=1-2 left comp34 on CPU34, the PoH core's SMT
# sibling, on the rc9 box. So the map is computed at boot (R10-3): each XDP
# core keeps its own queue's IRQ (mlx5_comp<core>) and no other, and every
# other mlx5 IRQ of the default-route NIC whose effective CPU is isolated, an
# XDP core included, moves to a non-isolated CPU, round-robin. IRQs are
# matched by <name>@pci:<bus-info> of that NIC, so a second port's IRQ is never
# taken for its own. The XDP set is rendered from state; the isolated set is
# the kernel's, read at boot.
_nic_render_mlx5_irq_script() {                   # <xdp cores, e.g. "1-2"; may be empty>
    local body
    body=$(cat <<'EOF'
#!/bin/bash
# Generated by DeePloy. Keep the mlx5 IRQs of the default-route NIC off the
# isolated CPUs: each XDP core keeps its own queue's IRQ (mlx5_comp<core>), and
# every other IRQ whose effective CPU is isolated, an XDP core included, moves
# to a non-isolated CPU, round-robin. Interface and PCI address computed at
# runtime (not hardcoded); only that address's IRQs are touched.
set -uo pipefail
XDP_CORES="__XDP_CORES__"
ROOT=${MLX5_IRQ_ROOT:-}         # tests: a fake / for /proc and /sys
log() { logger -t mlx5-irq "$*"; }
cpus() {                        # "1-2,10" -> "1 2 10 "
    local part i
    for part in ${1//,/ }; do
        if [[ $part == *-* ]]; then for ((i = ${part%-*}; i <= ${part#*-}; i++)); do printf '%s ' "$i"; done
        else printf '%s ' "$part"; fi
    done
}

NIC=$(ip route show default 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}')
[ -z "$NIC" ] && { log "no default-route NIC"; exit 1; }
BUS=$(ethtool -i "$NIC" 2>/dev/null | awk -F': ' '/^bus-info:/{print $2; exit}')
[ -z "$BUS" ] && { log "$NIC: no PCI address (ethtool -i bus-info)"; exit 1; }

ISOLATED=" $(cpus "$(cat "$ROOT/sys/devices/system/cpu/isolated" 2>/dev/null)")"
XDP=" $(cpus "$XDP_CORES")"
POOL=()                         # the non-isolated online CPUs, ascending
for c in $(cpus "$(cat "$ROOT/sys/devices/system/cpu/online" 2>/dev/null)"); do
    [[ $ISOLATED == *" $c "* ]] || POOL+=("$c")
done
[ ${#POOL[@]} -eq 0 ] && { log "no non-isolated online CPU"; exit 1; }

set_cpu() {                     # <irq> <name> <cpu>
    if echo "$3" > "$ROOT/proc/irq/$1/smp_affinity_list" 2>/dev/null; then log "$2 irq$1 -> cpu$3"
    else log "$2 irq$1: failed to set cpu$3"; fi
}

n=0 seen=0 kept=" "
while read -r irq name; do
    seen=$((seen + 1))
    q=${name#mlx5_comp}; q=${q%%@*}   # the queue of mlx5_comp<q>; not a number for any other name
    if [[ $XDP == *" $q "* ]]; then
        set_cpu "$irq" "$name" "$q"; kept+="$q "; continue
    fi
    for c in $(cpus "$(cat "$ROOT/proc/irq/$irq/effective_affinity_list" 2>/dev/null)"); do
        if [[ $ISOLATED == *" $c "* ]]; then
            set_cpu "$irq" "$name" "${POOL[n % ${#POOL[@]}]}"; n=$((n + 1)); break
        fi
    done
done < <(awk -v bus="$BUS" '{n = $NF; at = index(n, "@pci:")}
    at && substr(n, at + 5) == bus {sub(":", "", $1); print $1, n}' "$ROOT/proc/interrupts" 2>/dev/null)
[ "$seen" -eq 0 ] && log "$NIC: no mlx5 IRQ of pci:$BUS"
for c in $XDP; do [[ $kept == *" $c "* ]] || log "XDP core $c: no mlx5_comp$c@pci:$BUS"; done
exit 0
EOF
)
    printf '%s\n' "${body//__XDP_CORES__/$1}"
}

_nic_render_mlx5_service() {
    cat <<EOF
[Unit]
Description=Keep mlx5 IRQs off the isolated CPUs (XDP cores keep their own queue)
After=network.target
Before=solana.service

[Service]
Type=oneshot
ExecStart=${MLX5_IRQ_SCRIPT}
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
EOF
}

nic_mlx5_setup() {
    local xdp; xdp=$(state_get xdp_cores "")
    # Rendered into a script root runs at every boot: a CPU list or nothing.
    [[ -z "$xdp" || "$xdp" =~ ^[0-9]+(-[0-9]+)?(,[0-9]+(-[0-9]+)?)*$ ]] \
        || fail "state xdp_cores '${xdp}' is not a CPU list (e.g. 1-2) — not writing the mlx5 IRQ script"
    step "mlx5 IRQ-affinity service (Before=solana.service)"
    write_file "$MLX5_IRQ_SCRIPT"  "$(_nic_render_mlx5_irq_script "$xdp")" 0755
    write_file "$MLX5_IRQ_SERVICE" "$(_nic_render_mlx5_service)"
    run systemctl daemon-reload
    run systemctl enable mlx5-irq-affinity.service
    ok "mlx5-irq-affinity.service installed + enabled"
}

# --- bnxt_en: ring + offload tuning ------------------------------------------
_nic_render_bnxt_script() {
    cat <<'EOF'
#!/bin/bash
# Generated by DeePloy. bnxt_en ring + offload tuning for XDP. Interface
# computed at runtime (not hardcoded).
set -uo pipefail
NIC=$(ip route show default 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}')
[ -z "$NIC" ] && { logger -t nic-tuning "no default-route NIC"; exit 1; }
# Default rx/tx ring of 511 breaks XDP; bump to 512.
ethtool -G "$NIC" rx 512 tx 512 || logger -t nic-tuning "ring resize failed on $NIC"
# XDP needs these offloads disabled.
ethtool -K "$NIC" gro off lro off gso off tso off || logger -t nic-tuning "offload disable failed on $NIC"
logger -t nic-tuning "tuned $NIC (rings 512/512; gro/lro/gso/tso off)"
exit 0
EOF
}

_nic_render_bnxt_service() {
    cat <<EOF
[Unit]
Description=bnxt_en NIC ring + offload tuning for XDP
After=network.target
Before=solana.service

[Service]
Type=oneshot
ExecStart=${NIC_TUNING_SCRIPT}
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
EOF
}

# Pre-flight ZC compatibility test: verify the ring fix took before starting.
nic_bnxt_xdp_test() {
    step "bnxt_en XDP pre-flight (agave-xdp-compatibility against 8.8.8.8)"
    if is_dry_run; then
        info "${C_DIM}[dry-run]${C_NC} would clone+build ${XDP_COMPAT_REPO}, setcap, and test XDP against 8.8.8.8"
        return 0
    fi
    [[ -d "$XDP_COMPAT_SRC" ]] && run rm -rf "$XDP_COMPAT_SRC"
    run git clone "$XDP_COMPAT_REPO" "$XDP_COMPAT_SRC"
    # rustup installs cargo to ~/.cargo/bin, which isn't on the PATH nic.sh
    # inherits (Phase 4 sourced it only in its own context, and on --resume Phase 4
    # is skipped entirely). Resolve it the SAME way the toolchain build does.
    ensure_cargo_env
    if ! have cargo; then
        warn "cargo not found (rustup toolchain unavailable) — cannot build agave-xdp-compatibility to verify XDP"
        return 1
    fi
    if ! ( cd "$XDP_COMPAT_SRC" && cargo build --release ); then
        warn "agave-xdp-compatibility build failed — cannot verify XDP; do not start until resolved"
        return 1
    fi
    local bin nic
    bin=$(find "$XDP_COMPAT_SRC/target/release" -maxdepth 1 -type f -perm -u+x ! -name '*.d' 2>/dev/null | head -1)
    [[ -n "$bin" ]] || { warn "xdp-compat binary not found after build"; return 1; }
    run setcap cap_net_admin,cap_net_raw,cap_bpf,cap_perfmon+ep "$bin"
    nic=$(ip route show default 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}')
    # IP positional, interface as --xdp-interface, plus --timeout-ms (prod CLI).
    if "$bin" 8.8.8.8 --xdp-interface "$nic" --timeout-ms 1000; then
        ok "bnxt_en XDP verified (ring fix took)"
    else
        warn "bnxt_en XDP test FAILED — the ring/offload fix did not take. Do not start the validator."
        return 1
    fi
}

nic_bnxt_setup() {
    step "bnxt_en NIC tuning service (Before=solana.service)"
    write_file "$NIC_TUNING_SCRIPT"  "$(_nic_render_bnxt_script)" 0755
    write_file "$NIC_TUNING_SERVICE" "$(_nic_render_bnxt_service)"
    run systemctl daemon-reload
    run systemctl enable nic-tuning.service
    # ORDER MATTERS: apply the ring fix (rx 512) NOW, BEFORE the ZC pre-flight
    # test — with the default ring of 511 the XDP test always fails.
    run bash "$NIC_TUNING_SCRIPT"
    ok "nic-tuning.service installed + enabled (ring fix applied)"
    nic_bnxt_xdp_test || warn "Proceeding, but XDP is unverified on this bnxt_en box"
}

# --- orchestrator ------------------------------------------------------------
nic_run() {
    require_root
    nic_resolve_config
    case "$NIC_DRIVER" in
        mlx5_core) nic_mlx5_setup ;;
        bnxt_en)   nic_bnxt_setup ;;
        "")        warn "NIC driver unknown — skipping NIC-setup layer" ;;
        *)         info "No NIC-setup service for driver '${NIC_DRIVER}' (retransmit disabled)" ;;
    esac
}
